// Eight Bible courses after the two starters: the texts the church has always learned by heart (Psalm 23, the
// Lord's Prayer, the Shema and the priestly Blessing, the Ten Commandments), and four short themed courses (Fear,
// Worry and Peace; the Gospel; Easter; Who God Is). Each is short enough to light its window in a few weeks at
// five minutes a day.
//
// Scripture quotations are from the NASB 2020: NEW AMERICAN STANDARD BIBLE®, Copyright © 1960, 1971, 1977, 1995,
// 2020 by The Lockman Foundation. Used by permission. All rights reserved. lockman.org
// Every text is exactly as the NASB 2020 has it: whole verses, word for word, with their own capitals and
// punctuation, including quotation marks that open or close in a neighbouring verse. Only markup is left out
// (verse numbers, paragraph marks, italics and small capitals; the divine name is written LORD). A test checks
// each text against the publisher's HTML, kept in test/nasb-passages.json.
//
// For a verse, the cue (`prompt`) is its reference; for a commandment, its number and then its reference.

import type { Collection, Item, MeaningQuestion } from '../types.ts';

const SOURCE = 'New American Standard Bible (NASB 2020), © The Lockman Foundation. Used by permission.';

type Q = [phrase: string, question: string, answer: string, distractors: [string, string, string], explain: string];
const ask = ([phrase, question, answer, distractors, explain]: Q): MeaningQuestion => ({ phrase, question, answer, distractors, explain });

// One item: its cue, its words (as adult pieces, then the smaller child pieces) and one meaning question.
type Row = [prompt: string, adult: string[], child: string[], meaning: Q];

function collection(id: string, title: string, prefix: string, rows: Row[], unit = 'Verse'): Collection {
  const items: Item[] = rows.map(([prompt, adult, child, meaning], i) => ({
    id: `${prefix}-${i + 1}`, collection: id, number: i + 1, reviewed: false,
    prompt, text: adult.join(' '), chunks: { adult, child }, meaning: [ask(meaning)], connected: [],
  }));
  return { id, title, kind: 'scripture', unit, source: SOURCE, items };
}

