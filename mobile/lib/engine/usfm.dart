final _ref = RegExp(r'^(.+?) (\d+):(\d+)(?:[–-](\d+))?$');

String? toUsfm(String ref) {
  final m = _ref.firstMatch(ref.trim());
  final book = m == null ? null : _books[m.group(1)];
  if (m == null || book == null) return null;
  return '$book.${m.group(2)}.${m.group(3)}${m.group(4) != null ? '-${m.group(4)}' : ''}';
}

const _newTestament = {'MAT', 'MRK', 'LUK', 'JHN', 'ACT', 'ROM', '1CO', '2CO', 'GAL', 'EPH', 'PHP', 'COL', '1TH', '2TH', '1TI', '2TI', 'TIT', 'PHM', 'HEB', 'JAS', '1PE', '2PE', '1JN', '2JN', '3JN', 'JUD', 'REV'};

bool isOldTestament(String ref) {
  final u = toUsfm(ref);
  return u != null && !_newTestament.contains(u.split('.')[0]);
}

/// Only spacing is tidied; nothing else in the word of God is ever changed.
String tidyVerse(String text) => text.replaceAll(RegExp(r'\s+'), ' ').trim();
